function toPoints(segments) {
  return segments.map(([x, y]) => ({ x, y }));
}

export function letterPaths(char) {
  const key = String(char).toUpperCase();
  const seg = LETTER_SEGMENTS[key];
  if (!seg) return null;
  return { paths: [toPoints(seg)], color: "#5c7cfa" };
}

export function numberPaths(n) {
  const key = String(n);
  const seg = DIGIT_SEGMENTS[key];
  if (!seg) return null;
  return { paths: [toPoints(seg)], color: "#ff6b4a" };
}

export function shapePaths(shape) {
  switch (shape) {
    case "heart": {
      const pts = [];
      for (let i = 0; i <= 40; i++) {
        const t = (i / 40) * Math.PI * 2;
        const x = 0.5 + 0.22 * Math.pow(Math.sin(t), 3);
        const y = 0.48 - 0.24 * Math.cos(t) + 0.1 * Math.cos(2 * t);
        pts.push({ x, y });
      }
      return { paths: [pts], color: "#ff6b6b" };
    }
    case "star": {
      const pts = [];
      for (let i = 0; i <= 10; i++) {
        const r = i % 2 === 0 ? 0.38 : 0.16;
        const a = -Math.PI / 2 + (i / 10) * Math.PI * 2;
        pts.push({ x: 0.5 + r * Math.cos(a), y: 0.5 + r * Math.sin(a) });
      }
      return { paths: [pts], color: "#ffc857" };
    }
    case "diamond":
      return {
        paths: [toPoints([[0.5, 0.08], [0.88, 0.5], [0.5, 0.92], [0.12, 0.5], [0.5, 0.08]])],
        color: "#4ecdc4",
      };
    case "arrow":
      return {
        paths: [
          toPoints([
            [0.15, 0.5], [0.55, 0.5], [0.55, 0.3], [0.85, 0.5], [0.55, 0.7], [0.55, 0.5],
          ]),
        ],
        color: "#6bcb77",
      };
    case "house":
      return {
        paths: [
          toPoints([
            [0.2, 0.55], [0.2, 0.9], [0.8, 0.9], [0.8, 0.55], [0.5, 0.15], [0.2, 0.55],
          ]),
          toPoints([[0.38, 0.9], [0.38, 0.68], [0.62, 0.68], [0.62, 0.9]]),
        ],
        color: "#f4a261",
      };
    default:
      return null;
  }
}

export function listGeneratedPictures() {
  const items = [];
  for (const ch of "ABCDEFGHIJKLMNOPQRSTUVWXYZ") {
    items.push({
      id: `letter-${ch.toLowerCase()}`,
      name: ch,
      category: "letters",
      generated: "letter",
      glyph: ch,
      color: "#5c7cfa",
    });
  }
  for (let n = 0; n <= 9; n++) {
    items.push({
      id: `number-${n}`,
      name: String(n),
      category: "letters",
      generated: "number",
      glyph: String(n),
      color: "#ff6b4a",
    });
  }
  for (const shape of ["heart", "star", "diamond", "arrow", "house"]) {
    items.push({
      id: `shape-${shape}`,
      name: shape.charAt(0).toUpperCase() + shape.slice(1),
      category: "shapes",
      generated: "shape",
      glyph: shape,
    });
  }
  return items;
}

export function resolveGeneratedPicture(meta) {
  if (meta.generated === "letter") return letterPaths(meta.glyph);
  if (meta.generated === "number") return numberPaths(meta.glyph);
  if (meta.generated === "shape") return shapePaths(meta.glyph);
  return null;
}
