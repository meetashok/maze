/**
 * Algorithmic dot paths for letters, numbers, and geometric shapes.
 * Coordinates are normalized 0–1 in a square view box.
 */

function rect(x, y, w, h) {
  return [
    [x, y],
    [x + w, y],
    [x + w, y + h],
    [x, y + h],
    [x, y],
  ];
}

